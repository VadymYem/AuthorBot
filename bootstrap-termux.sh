  resolve_repository
  ui_run git -C "$APP_DIR" remote set-url origin "$REPO_URL"
  ui_run git -C "$APP_DIR" fetch origin main
  ui_run git -C "$APP_DIR" merge --ff-only origin/main
elif [ -e "$APP_DIR" ]; then
  printf '%s уже існує і не є Git-репозиторієм.\n' "$APP_DIR" >>"$LOG_FILE"
  ui_fail
