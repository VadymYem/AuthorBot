ui_cleanup() {
  if [ "${UI_TTY:-0}" = 1 ]; then printf '\033[0m\033[?25h'; fi
  if [ -n "${UI_CHILD:-}" ]; then kill "$UI_CHILD" 2>/dev/null || true; fi
  if [ -n "${AUTHORBOT_PROGRESS_FILE:-}" ]; then rm -f "$AUTHORBOT_PROGRESS_FILE"; fi
}

ui_link() {
  if [ "${UI_TTY:-0}" = 1 ]; then printf '%*s' "$(( (UI_WIDTH - ${#2}) / 2 ))" ''; fi
  printf '\033]8;;%s\033\\%s\033]8;;\033\\\n' "$1" "$2"
}

ui_fail() {
  ui_cleanup
  printf '\nНе вдалося завершити: %s.\nЖурнал: %s\n' "${UI_LABEL:-встановлення}" "$LOG_FILE" >&2
  printf 'Повтори встановлення після усунення причини; твої сесії збережено.\n' >&2
}

ui_init() {
  LOG_FILE="${AUTHORBOT_LOG_FILE:-$HOME/authorbot-install.log}"
  umask 077
  if [ -z "${AUTHORBOT_LOG_INITIALIZED:-}" ]; then : >"$LOG_FILE"; fi
  export AUTHORBOT_LOG_FILE="$LOG_FILE" AUTHORBOT_LOG_INITIALIZED=1
  UI_TTY=0
  UI_STAGE=0
  UI_DRAWN=0
  UI_LAST_STAGE=-1
  UI_LABEL=Підготовка
  UI_WIDTH=40
  UI_CHILD=
  UI_BUSY=0
  UI_FRAME=0
  if [ -t 1 ] && [ "${TERM:-dumb}" != dumb ]; then
    UI_TTY=1
    local size rows columns
    size="$(stty size 2>/dev/null || true)"
    read -r rows columns <<< "$size" || true
    if [[ "${columns:-}" =~ ^[0-9]+$ ]] && [ "$columns" -ge 28 ]; then UI_WIDTH="$columns"; fi
    [ "$UI_WIDTH" -le 60 ] || UI_WIDTH=60
    clear 2>/dev/null || printf '\033[2J\033[H'
    printf '\033[?25l'
    ui_logo
    printf '\n%*s' "$(( (UI_WIDTH - 22) / 2 ))" ''
    printf '\033[1;38;2;230;188;116mAuthorBot\033[0m \033[2mby AuthorChe\033[0m\n\n'
    printf '\033[38;2;124;177;173m'
    ui_link 'https://authorche.top' 'authorche.top'
    printf '\033[0m'
    ui_link 'https://t.me/wsinfo' 't.me/wsinfo'
    ui_link 'https://github.com/VadymYem/AuthorBot' 'GitHub · VadymYem/AuthorBot'
    printf '\n'
  else
    printf 'AuthorBot by AuthorChe\nauthorche.top · t.me/wsinfo\ngithub.com/VadymYem/AuthorBot\n\n'
  fi
  trap ui_cleanup EXIT
  trap 'ui_fail' ERR
  trap 'ui_cleanup; exit 130' INT
  trap 'ui_cleanup; exit 143' TERM HUP
}

ui_draw() {
  local percent filled remaining width bar='' spaces='' i spinner=''
  percent=$(( (UI_STAGE - 1) * 100 / 8 ))
  if [ "$UI_STAGE" -ge 9 ]; then percent=100; fi
  if [ "$UI_TTY" = 0 ]; then
    if [ "$UI_LAST_STAGE" != "$UI_STAGE" ]; then
      printf '%3d%% · %s\n' "$percent" "$UI_LABEL"
      UI_LAST_STAGE="$UI_STAGE"
    fi
    return
  fi
  width=$(( UI_WIDTH - 9 ))
  filled=$(( width * percent / 100 ))
  remaining=$(( 100 - percent ))
  for ((i=0; i<filled; i++)); do bar+='━'; done
  for ((i=filled; i<width; i++)); do spaces+='─'; done
  if [ "$UI_DRAWN" = 1 ]; then printf '\033[3A'; fi
  if [ "$UI_BUSY" = 1 ]; then
    local frames=('◐' '◓' '◑' '◒')
    spinner=" ${frames[UI_FRAME % 4]}"
    UI_FRAME=$(( UI_FRAME + 1 ))
  fi
  printf '\033[2K\r\033[1m%s%s\033[0m\n' "$UI_LABEL" "$spinner"
  printf '\033[2K\r\033[38;2;230;188;116m%s\033[38;2;54;65;67m%s\033[0m %3d%%\n' "$bar" "$spaces" "$percent"
  printf '\033[2K\r\033[2mЗалишилося: %d%% етапів\033[0m\n' "$remaining"
  UI_DRAWN=1
}

ui_stage() { UI_STAGE="$1"; UI_LABEL="$2"; ui_draw; }

ui_read_progress() {
  local stage label
  if [ -n "${AUTHORBOT_PROGRESS_FILE:-}" ] && [ -f "$AUTHORBOT_PROGRESS_FILE" ]; then
    IFS='|' read -r stage label <"$AUTHORBOT_PROGRESS_FILE" || return 0
    if [[ "$stage" =~ ^[4-7]$ ]] && [ "$stage" -gt "$UI_STAGE" ]; then ui_stage "$stage" "$label"; fi
  fi
}

ui_run() {
  # Only noninteractive installation runs in the background. Never authentication.
  "$@" </dev/null >>"$LOG_FILE" 2>&1 &
  UI_CHILD=$!
  UI_BUSY=1
  while kill -0 "$UI_CHILD" 2>/dev/null; do ui_read_progress; ui_draw; sleep 0.2; done
  local status=0
  wait "$UI_CHILD" || status=$?
  UI_CHILD=
  UI_BUSY=0
  ui_read_progress
  return "$status"
}

ui_finish() {
  ui_stage 9 'Встановлення завершено'
  ui_cleanup
  trap - ERR INT TERM HUP
  printf '\nНаступний запуск: authorbot\n\n'
}

